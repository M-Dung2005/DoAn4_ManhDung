import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const directory = resolve('../../docs/previews');
const backend = process.env.SMARTSHOP_BACKEND_URL || 'http://localhost:3000';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5176/login');
  await page.getByRole('heading', { name: 'Đăng nhập quản trị' }).waitFor();
  await page.screenshot({ path: resolve(directory, 'admin-login.png'), fullPage: true });
  await page.getByLabel('Tên đăng nhập').fill('admin');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('123456');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await page.waitForURL('**/dashboard');
  await page.goto('http://127.0.0.1:5176/categories');
  await page.locator('.category-tile').first().waitFor();
  await page.screenshot({ path: resolve(directory, 'admin-categories.png'), fullPage: true });
  await page.locator('.category-tile').filter({ hasText: 'Thời trang' }).click();
  if (await page.getByLabel('Tìm kiếm', { exact: true }).inputValue() !== 'Thời trang') throw new Error('Category quick filter did not update');
  await page.goto('http://127.0.0.1:5176/products');
  await page.locator('.admin-product-card').first().waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.admin-product-image img')].every(image => image.complete && image.naturalWidth > 0));
  await page.screenshot({ path: resolve(directory, 'admin-products.png'), fullPage: true });
  await page.getByText('Bảng', { exact: true }).click();
  await page.getByRole('cell', { name: 'Sổ ghi chép Minimal A6' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:5176/categories');
  await page.locator('.category-tile').first().waitFor();
  await page.screenshot({ path: resolve(directory, 'admin-mobile.png'), fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Admin viewport overflows');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  mobile.setDefaultTimeout(15000);
  mobile.on('pageerror', error => { errors.push(error.message); console.log('Shop error:', error.stack); });
  mobile.on('console', message => { if (message.type() === 'error') console.log('Shop console:', message.text()); });
  mobile.on('requestfailed', request => console.log('Shop request failed:', request.url(), request.failure()?.errorText));
  await mobile.route('**/api/**', async route => {
    const original = new URL(route.request().url());
    await route.fulfill({ response: await route.fetch({ url: `${backend}${original.pathname}${original.search}` }) });
  });
  const auth = await fetch(backend + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ten_dang_nhap: 'khachhang', mat_khau: '123456' }) }).then(response => response.json());
  if (!auth.success) throw new Error(auth.message);
  await mobile.addInitScript(data => { localStorage.setItem('token', data.token); localStorage.setItem('user', JSON.stringify(data.user)); if (data.refresh_token) localStorage.setItem('refresh_token', data.refresh_token); }, auth.data);
  await mobile.goto(process.env.SMARTSHOP_SHOP_URL || 'http://localhost:8083/');
  await mobile.getByText('SMARTSHOP', { exact: true }).waitFor();
  await mobile.getByText('Thời trang', { exact: true }).waitFor();
  await mobile.waitForFunction(() => [...document.querySelectorAll('img')].every(image => image.complete && image.naturalWidth > 0));
  await mobile.screenshot({ path: resolve(directory, 'shop-home.png'), fullPage: true });
  await mobile.getByText('Thời trang', { exact: true }).click();
  await mobile.getByText('Áo thun cotton Essential', { exact: true }).last().waitFor();
  await mobile.screenshot({ path: resolve(directory, 'shop-products.png'), fullPage: true });
  await mobile.getByText('Áo thun cotton Essential', { exact: true }).click();
  await mobile.getByText('Trắng / L', { exact: true }).waitFor();
  await mobile.getByText('Trắng / L', { exact: true }).click();
  await mobile.screenshot({ path: resolve(directory, 'shop-product-detail.png'), fullPage: true });
  await mobile.getByRole('button', { name: 'Thanh toán ngay', exact: true }).click();
  await mobile.getByText('Thanh toán', { exact: true }).first().waitFor();
  await mobile.getByText('Áo thun cotton Essential - Trắng / L', { exact: true }).waitFor();
  await mobile.screenshot({ path: resolve(directory, 'shop-checkout.png'), fullPage: true });
  await fetch(backend + '/api/auth/logout', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${auth.data.token}` }, body: JSON.stringify({ refresh_token: auth.data.refresh_token }) });
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  console.log('Preview screenshots:', directory);
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Browser verification passed: admin grids/tables/categories/responsive layout, shopper categories/variant selection/buy-now checkout.');
} finally { await browser.close(); }
